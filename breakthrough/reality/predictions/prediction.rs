use std::collections::VecDeque;
use std::fmt;

use super::model::PredictionModel;
use super::uncertainty::{Uncertainty, TrendDirection};
use crate::RealityError;

/// Forecast: A time-series prediction of future values.
///
/// Forecasts extend predictions across a temporal horizon,
/// providing a sequence of predicted values with confidence intervals.
#[derive(Debug, Clone, PartialEq)]
pub struct Forecast {
    /// Unique identifier for this forecast.
    pub id: String,
    /// The model used to generate this forecast.
    pub model: PredictionModel,
    /// Predicted values over the forecast horizon.
    pub values: VecDeque<f64>,
    /// Confidence intervals for each predicted value.
    pub confidence_intervals: VecDeque<Uncertainty>,
    /// Starting timestamp of the forecast.
    pub start_timestamp: f64,
    /// Time step between forecast points.
    pub time_step: f64,
    /// Predicted trend direction.
    pub trend: TrendDirection,
}

impl Forecast {
    /// Minimum forecast horizon length.
    pub const MIN_HORIZON: usize = 1;
    /// Maximum forecast horizon length.
    pub const MAX_HORIZON: usize = 10000;

    /// Creates a new forecast.
    ///
    /// # Errors
    /// Returns `RealityError::InvalidMeasurement` if horizon is out of range or time_step is not positive.
    pub fn new(
        id: impl Into<String>,
        model: PredictionModel,
        start_timestamp: f64,
        time_step: f64,
        horizon: usize,
    ) -> Result<Self, RealityError> {
        if horizon < Self::MIN_HORIZON || horizon > Self::MAX_HORIZON {
            return Err(RealityError::CapacityExceeded {
                max: Self::MAX_HORIZON,
                attempted: horizon,
            });
        }
        if time_step <= 0.0 {
            return Err(RealityError::InvalidMeasurement {
                value: time_step,
                reason: "time_step must be positive".to_string(),
            });
        }
        Ok(Self {
            id: id.into(),
            model,
            values: VecDeque::with_capacity(horizon),
            confidence_intervals: VecDeque::with_capacity(horizon),
            start_timestamp,
            time_step,
            trend: TrendDirection::Unknown,
        })
    }

    /// Adds a predicted value with its uncertainty.
    pub fn add_step(&mut self, value: f64, uncertainty: Uncertainty) {
        self.values.push_back(value);
        self.confidence_intervals.push_back(uncertainty);
    }

    /// Returns the timestamp for the i-th forecast step.
    pub fn timestamp_for_step(&self, step: usize) -> f64 {
        self.start_timestamp + step as f64 * self.time_step
    }

    /// Returns the predicted value at a given step.
    pub fn value_at_step(&self, step: usize) -> Option<f64> {
        self.values.get(step).copied()
    }

    /// Returns the uncertainty at a given step.
    pub fn uncertainty_at_step(&self, step: usize) -> Option<&Uncertainty> {
        self.confidence_intervals.get(step)
    }

    /// Returns the length of the forecast horizon.
    pub fn horizon_length(&self) -> usize {
        self.values.len()
    }

    /// Fills the forecast with values generated by a simple linear extrapolation.
    pub fn fill_linear(&mut self, last_value: f64, slope: f64) {
        for i in 0..self.values.capacity() {
            let value = last_value + slope * i as f64;
            self.values.push_back(value);
            let uncertainty = Uncertainty::symmetric(0.1 * (1.0 + i as f64 * 0.1), 0.95).unwrap();
            self.confidence_intervals.push_back(uncertainty);
        }
        if slope > 0.01 {
            self.trend = TrendDirection::Increasing;
        } else if slope < -0.01 {
            self.trend = TrendDirection::Decreasing;
        } else {
            self.trend = TrendDirection::Stable;
        }
    }
}

/// Prediction: A single predicted future state.
///
/// Predictions are point estimates of future observations, accompanied
/// by uncertainty quantification.
#[derive(Debug, Clone, PartialEq)]
pub struct Prediction {
    /// Unique identifier for this prediction.
    pub id: String,
    /// The model that generated this prediction.
    pub model_id: String,
    /// Predicted value.
    pub value: f64,
    /// Uncertainty in the prediction.
    pub uncertainty: Uncertainty,
    /// Timestamp at which the prediction is made.
    pub predicted_at: f64,
    /// Timestamp for which the prediction applies.
    pub target_timestamp: f64,
    /// Predicted trend direction.
    pub trend: TrendDirection,
    /// Confidence in the prediction (0.0 to 1.0).
    pub confidence: f64,
}

impl Prediction {
    /// Minimum valid confidence value.
    pub const MIN_CONFIDENCE: f64 = 0.0;
    /// Maximum valid confidence value.
    pub const MAX_CONFIDENCE: f64 = 1.0;

    /// Creates a new prediction.
    ///
    /// # Errors
    /// Returns `RealityError::OutOfRange` if confidence is out of range or timestamps are invalid.
    pub fn new(
        id: impl Into<String>,
        model_id: impl Into<String>,
        value: f64,
        uncertainty: Uncertainty,
        predicted_at: f64,
        target_timestamp: f64,
        trend: TrendDirection,
        confidence: f64,
    ) -> Result<Self, RealityError> {
        if confidence < Self::MIN_CONFIDENCE || confidence > Self::MAX_CONFIDENCE {
            return Err(RealityError::OutOfRange {
                field: "confidence".to_string(),
                value: confidence,
                min: Self::MIN_CONFIDENCE,
                max: Self::MAX_CONFIDENCE,
            });
        }
        if predicted_at > target_timestamp {
            return Err(RealityError::InvalidState(
                "predicted_at must be <= target_timestamp".to_string(),
            ));
        }
        Ok(Self {
            id: id.into(),
            model_id: model_id.into(),
            value,
            uncertainty,
            predicted_at,
            target_timestamp,
            trend,
            confidence,
        })
    }

    /// Returns the prediction horizon (target_timestamp - predicted_at).
    pub fn horizon(&self) -> f64 {
        self.target_timestamp - self.predicted_at
    }

    /// Returns whether the prediction is for the future.
    pub fn is_future(&self, now: f64) -> bool {
        self.target_timestamp > now
    }

    /// Returns whether this prediction has expired.
    pub fn is_expired(&self, now: f64) -> bool {
        now > self.target_timestamp
    }

    /// Updates the prediction with an observed value and returns the error.
    pub fn verify(&mut self, observed: f64) -> f64 {
        let error = (self.value - observed).abs();
        self.uncertainty = Uncertainty::new(
            error,
            self.value - error * 2.0,
            self.value + error * 2.0,
            self.uncertainty.confidence_level,
        ).unwrap_or(self.uncertainty);
        error
    }
}

